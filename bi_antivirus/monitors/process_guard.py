"""
BI Antivirus - Process Guard & Privilege Security Sentinel
Provides safe, defensive, read-only process token auditing, PPID spoofing detection,
and critical process handle security monitoring:
1. Token Privilege Auditing:
   Detects unauthorized or anomalous elevation of high-risk Windows privileges
   (SeDebugPrivilege, SeTcbPrivilege, SeLoadDriverPrivilege, SeImpersonatePrivilege)
   held by non-system processes or untrusted script/terminal interpreters.
2. PPID (Parent Process ID) Spoofing Detection:
   Identifies deceptive parent-child process relationships (e.g. cmd.exe claiming
   lsass.exe or csrss.exe as parent, or creation time order anomalies).
3. Critical Handle Auditing:
   Detects suspicious open handles targeting lsass.exe or csrss.exe with memory read/write
   rights (PROCESS_VM_READ, PROCESS_VM_WRITE, PROCESS_ALL_ACCESS) associated with credential theft.

Strictly non-invasive: Zero arbitrary process termination without authorization,
handles AccessDenied safely, and operates 100% locally.
"""

import os
import sys
import time
import logging
from dataclasses import dataclass, field, asdict
from pathlib import Path
from typing import Dict, Any, List, Optional, Set, Tuple

logger = logging.getLogger("BI_ProcessGuard")

IS_WINDOWS = sys.platform.startswith("win")

# High-risk Win32 privileges commonly abused for privilege escalation or credential access
HIGH_RISK_PRIVILEGES = {
    "SeDebugPrivilege": {
        "description": "Debug programs (allows inspecting/modifying arbitrary process memory)",
        "mitre_technique": "T1134.001",
        "severity": "HIGH",
    },
    "SeTcbPrivilege": {
        "description": "Act as part of operating system (subsystem authority)",
        "mitre_technique": "T1134.001",
        "severity": "CRITICAL",
    },
    "SeLoadDriverPrivilege": {
        "description": "Load and unload device drivers (vulnerable to BYOVD exploits)",
        "mitre_technique": "T1068",
        "severity": "HIGH",
    },
    "SeImpersonatePrivilege": {
        "description": "Impersonate a client after authentication (token potato exploits)",
        "mitre_technique": "T1134.001",
        "severity": "HIGH",
    },
    "SeTakeOwnershipPrivilege": {
        "description": "Take ownership of files or other objects",
        "mitre_technique": "T1078",
        "severity": "MEDIUM",
    },
}

# Processes that normally should NOT hold SeDebugPrivilege unless under attack
UNTRUSTED_DEBUG_PRIV_PROCESSES = {
    "cmd.exe", "powershell.exe", "pwsh.exe", "wscript.exe", "cscript.exe",
    "rundll32.exe", "regsvr32.exe", "mshta.exe", "certutil.exe", "python.exe",
}

# Known system processes that NEVER legitimately spawn interactive terminals
DISALLOWED_TERMINAL_PARENTS = {
    "lsass.exe", "csrss.exe", "smss.exe", "wininit.exe", "spoolsv.exe"
}

# Dangerous Process Access Rights
PROCESS_TERMINATE = 0x0001
PROCESS_CREATE_THREAD = 0x0002
PROCESS_VM_OPERATION = 0x0008
PROCESS_VM_READ = 0x0010
PROCESS_VM_WRITE = 0x0020
PROCESS_DUP_HANDLE = 0x0040
PROCESS_CREATE_PROCESS = 0x0080
PROCESS_SET_QUOTA = 0x0100
PROCESS_SET_INFORMATION = 0x0200
PROCESS_QUERY_INFORMATION = 0x0400
PROCESS_SUSPEND_RESUME = 0x0800
PROCESS_QUERY_LIMITED_INFORMATION = 0x1000
PROCESS_ALL_ACCESS = 0x1F0FFF

DANGEROUS_LSASS_ACCESS_MASK = (
    PROCESS_VM_READ | PROCESS_VM_WRITE | PROCESS_CREATE_THREAD | PROCESS_DUP_HANDLE | PROCESS_ALL_ACCESS
)


@dataclass
class ProcessGuardAlert:
    """Diagnostic security alert generated by process guard."""
    alert_type: str  # TOKEN_PRIVILEGE_THEFT, PPID_SPOOFING, CRITICAL_HANDLE_THEFT
    severity: str    # CRITICAL, HIGH, MEDIUM, LOW
    pid: int
    process_name: str
    target_pid: Optional[int] = None
    target_name: Optional[str] = None
    mitre_tactic: str = "Privilege Escalation"
    mitre_technique: str = "T1134"
    summary: str = ""
    details: Dict[str, Any] = field(default_factory=dict)
    timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class ProcessGuard:
    """Defensive Sentinel inspecting process tokens, PPID anomalies, and critical handles."""

    def __init__(self, history_db: Optional[Any] = None):
        self.history_db = history_db
        self.alerts_history: List[ProcessGuardAlert] = []

    def audit_process_token(
        self,
        pid: int,
        process_name: Optional[str] = None,
        image_path: Optional[str] = None,
        simulated_privileges: Optional[List[str]] = None,
    ) -> List[ProcessGuardAlert]:
        """
        Inspect process token privileges:
        Flags non-system processes that possess elevated or dangerous tokens.
        """
        alerts = []
        pname = (process_name or f"PID_{pid}").lower()
        privileges_found: List[str] = []

        if simulated_privileges is not None:
            privileges_found = simulated_privileges
        elif IS_WINDOWS and pid > 4:
            privileges_found = self._query_win32_token_privileges(pid)

        for priv in privileges_found:
            priv_info = HIGH_RISK_PRIVILEGES.get(priv)
            if not priv_info:
                continue

            # Check if process is an untrusted host or outside System32
            is_untrusted_name = pname in UNTRUSTED_DEBUG_PRIV_PROCESSES
            is_non_system_dir = False
            if image_path:
                norm_path = image_path.lower()
                is_non_system_dir = not (
                    norm_path.startswith(r"c:\windows\system32")
                    or norm_path.startswith(r"c:\windows\syswow64")
                )

            # High severity condition: terminal/script host or non-system binary holding debug/tcb privileges
            if is_untrusted_name or is_non_system_dir or priv in ("SeDebugPrivilege", "SeTcbPrivilege"):
                alert = ProcessGuardAlert(
                    alert_type="TOKEN_PRIVILEGE_ANOMALY",
                    severity=priv_info["severity"],
                    pid=pid,
                    process_name=process_name or pname,
                    mitre_tactic="Privilege Escalation",
                    mitre_technique=priv_info["mitre_technique"],
                    summary=f"Suspicious token privilege detected in {process_name or pname}: {priv} ({priv_info['description']})",
                    details={
                        "privilege": priv,
                        "description": priv_info["description"],
                        "image_path": image_path or "UNKNOWN",
                        "is_untrusted_binary": is_untrusted_name,
                    },
                )
                alerts.append(alert)
                self._record_alert(alert)

        return alerts

    def audit_ppid_spoofing(
        self,
        pid: int,
        ppid: int,
        process_name: str,
        parent_name: Optional[str] = None,
        create_time: Optional[float] = None,
        parent_create_time: Optional[float] = None,
        image_path: Optional[str] = None,
    ) -> List[ProcessGuardAlert]:
        """
        Detect Parent Process ID (PPID) spoofing anomalies:
        1. Disallowed parent: lsass/csrss/smss spawning interactive shells or non-system binaries.
        2. Time inversion: Child creation timestamp is earlier than reported parent creation timestamp.
        3. Path anomaly: Process claiming services.exe as parent but located in user AppData/Temp.
        """
        alerts = []
        p_clean = process_name.lower().strip()
        parent_clean = (parent_name or "").lower().strip()

        # 1. Disallowed parent hierarchy check
        if parent_clean in DISALLOWED_TERMINAL_PARENTS:
            if p_clean in ("cmd.exe", "powershell.exe", "pwsh.exe", "wscript.exe", "cscript.exe", "rundll32.exe"):
                alert = ProcessGuardAlert(
                    alert_type="PPID_SPOOFING_DISALLOWED_PARENT",
                    severity="CRITICAL",
                    pid=pid,
                    process_name=process_name,
                    target_pid=ppid,
                    target_name=parent_name,
                    mitre_tactic="Defense Evasion",
                    mitre_technique="T1134.004",
                    summary=f"PPID Spoofing: {process_name} reported illegitimate parent {parent_name} (PID {ppid})",
                    details={
                        "rule": "System critical processes do not spawn interactive script hosts",
                        "parent": parent_name,
                        "child": process_name,
                    },
                )
                alerts.append(alert)
                self._record_alert(alert)

        # 2. Creation time order anomaly
        if create_time is not None and parent_create_time is not None:
            # If child was created before parent existed (allow 0.1s clock tolerance)
            if create_time < parent_create_time - 0.1:
                alert = ProcessGuardAlert(
                    alert_type="PPID_SPOOFING_TIME_INVERSION",
                    severity="HIGH",
                    pid=pid,
                    process_name=process_name,
                    target_pid=ppid,
                    target_name=parent_name,
                    mitre_tactic="Defense Evasion",
                    mitre_technique="T1134.004",
                    summary=f"PPID Time Inversion: {process_name} creation timestamp ({create_time:.2f}) precedes parent {parent_name} ({parent_create_time:.2f})",
                    details={
                        "child_create_time": create_time,
                        "parent_create_time": parent_create_time,
                        "time_delta": parent_create_time - create_time,
                    },
                )
                alerts.append(alert)
                self._record_alert(alert)

        # 3. Path anomaly under services.exe
        if parent_clean == "services.exe" and image_path:
            norm_path = image_path.lower()
            if any(susp in norm_path for susp in ("\\temp\\", "\\appdata\\", "\\users\\", "\\downloads\\")):
                alert = ProcessGuardAlert(
                    alert_type="PPID_SPOOFING_SERVICES_PATH_ANOMALY",
                    severity="HIGH",
                    pid=pid,
                    process_name=process_name,
                    target_pid=ppid,
                    target_name=parent_name,
                    mitre_tactic="Defense Evasion",
                    mitre_technique="T1134.004",
                    summary=f"Services.exe child path anomaly: {process_name} running from user space ({image_path})",
                    details={"image_path": image_path},
                )
                alerts.append(alert)
                self._record_alert(alert)

        return alerts

    def audit_critical_handle(
        self,
        source_pid: int,
        source_name: str,
        target_pid: int,
        target_name: str,
        desired_access: int,
    ) -> Optional[ProcessGuardAlert]:
        """
        Audit open process handle requests targeting LSASS or CSRSS.
        Flags access masks requesting memory read/write or handle duplication rights.
        """
        t_clean = target_name.lower().strip()
        s_clean = source_name.lower().strip()

        # Target must be sensitive process (lsass.exe or csrss.exe)
        if t_clean not in ("lsass.exe", "csrss.exe"):
            return None

        # Exclude legitimate Windows core services
        if s_clean in ("services.exe", "csrss.exe", "smss.exe", "svchost.exe", "wininit.exe"):
            return None

        # Evaluate dangerous access mask
        has_dangerous_access = bool(desired_access & DANGEROUS_LSASS_ACCESS_MASK)
        if has_dangerous_access:
            rights = []
            if desired_access & PROCESS_VM_READ:
                rights.append("PROCESS_VM_READ")
            if desired_access & PROCESS_VM_WRITE:
                rights.append("PROCESS_VM_WRITE")
            if desired_access & PROCESS_CREATE_THREAD:
                rights.append("PROCESS_CREATE_THREAD")
            if desired_access & PROCESS_DUP_HANDLE:
                rights.append("PROCESS_DUP_HANDLE")
            if desired_access & PROCESS_ALL_ACCESS == PROCESS_ALL_ACCESS:
                rights.append("PROCESS_ALL_ACCESS")

            alert = ProcessGuardAlert(
                alert_type="CRITICAL_HANDLE_THEFT_ATTEMPT",
                severity="CRITICAL",
                pid=source_pid,
                process_name=source_name,
                target_pid=target_pid,
                target_name=target_name,
                mitre_tactic="Credential Access",
                mitre_technique="T1003.001",
                summary=f"Unauthorized memory handle attempt: {source_name} (PID {source_pid}) requested {', '.join(rights)} on {target_name}",
                details={
                    "desired_access_mask": hex(desired_access),
                    "rights_detected": rights,
                    "target_process": target_name,
                },
            )
            self._record_alert(alert)
            return alert

        return None

    def _query_win32_token_privileges(self, pid: int) -> List[str]:
        """Query Win32 process token privileges safely."""
        privileges: List[str] = []
        try:
            import ctypes
            from ctypes import wintypes

            advapi32 = ctypes.windll.advapi32
            kernel32 = ctypes.windll.kernel32

            PROCESS_QUERY_LIMITED_INFORMATION = 0x1000
            TOKEN_QUERY = 0x0008

            h_proc = kernel32.OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, False, pid)
            if not h_proc:
                return []

            try:
                h_token = wintypes.HANDLE()
                if advapi32.OpenProcessToken(h_proc, TOKEN_QUERY, ctypes.byref(h_token)):
                    try:
                        # Query TokenPrivileges length
                        TokenPrivileges = 3
                        length = wintypes.DWORD(0)
                        advapi32.GetTokenInformation(h_token, TokenPrivileges, None, 0, ctypes.byref(length))
                        if length.value > 0:
                            buf = ctypes.create_string_buffer(length.value)
                            if advapi32.GetTokenInformation(h_token, TokenPrivileges, buf, length.value, ctypes.byref(length)):
                                count = ctypes.c_ulong.from_buffer_copy(buf[0:4]).value
                                for i in range(min(count, 64)):
                                    offset = 4 + (i * 12)
                                    if offset + 12 <= length.value:
                                        luid_low = ctypes.c_ulong.from_buffer_copy(buf[offset:offset + 4]).value
                                        luid_high = ctypes.c_long.from_buffer_copy(buf[offset + 4:offset + 8]).value
                                        attrs = ctypes.c_ulong.from_buffer_copy(buf[offset + 8:offset + 12]).value

                                        # Lookup privilege name
                                        name_buf = ctypes.create_unicode_buffer(128)
                                        name_len = wintypes.DWORD(128)
                                        luid = (luid_low, luid_high)
                                        # Use standard known LUID mappings or LookupPrivilegeNameW
                                        if advapi32.LookupPrivilegeNameW(None, buf[offset:offset + 8], name_buf, ctypes.byref(name_len)):
                                            p_name = name_buf.value
                                            # Check if SE_PRIVILEGE_ENABLED (0x00000002)
                                            if attrs & 0x00000002:
                                                privileges.append(p_name)
                    finally:
                        kernel32.CloseHandle(h_token)
            finally:
                kernel32.CloseHandle(h_proc)

        except Exception as e:
            logger.debug(f"Failed querying token privileges for PID {pid}: {e}")

        return privileges

    def _record_alert(self, alert: ProcessGuardAlert) -> None:
        """Record alert to internal history and database."""
        self.alerts_history.append(alert)
        if len(self.alerts_history) > 500:
            self.alerts_history.pop(0)

        logger.warning(f"PROCESS GUARD ALERT: {alert.summary}")

        if self.history_db and hasattr(self.history_db, "record_threat"):
            try:
                self.history_db.record_threat(
                    session_id="PROCESS-GUARD",
                    file_path=f"pid://{alert.pid}/{alert.process_name}",
                    file_hash="PROCESS_DEFENSE",
                    file_size=0,
                    threat_name=f"ProcessGuard.{alert.alert_type}",
                    threat_family="ProcessSecurity",
                    severity=alert.severity,
                    action_taken="LOGGED_ALERT",
                    details=alert.summary,
                )
            except Exception as e:
                logger.debug(f"Failed recording process guard alert in history db: {e}")

    def get_guard_status(self) -> Dict[str, Any]:
        """Return diagnostic metrics of ProcessGuard."""
        return {
            "alerts_total": len(self.alerts_history),
            "critical_alerts": sum(1 for a in self.alerts_history if a.severity == "CRITICAL"),
            "high_alerts": sum(1 for a in self.alerts_history if a.severity == "HIGH"),
            "medium_alerts": sum(1 for a in self.alerts_history if a.severity == "MEDIUM"),
            "recent_alerts": [a.to_dict() for a in self.alerts_history[-10:]],
        }
