import os
import sys
import time
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional

from bi_antivirus.config import REPORTS_DIR, APP_NAME, APP_VERSION
from bi_antivirus.enterprise.fleet_manager import FleetManager
from bi_antivirus.database.history import HistoryDatabase

logger = logging.getLogger("BI_ComplianceReporter")

DISCLAIMER_NOTICE = (
    "NOTICE: This technical posture assessment report is generated automatically by BI Antivirus. "
    "All findings reflect empirical measurements of endpoint configurations, active telemetry, "
    "threat intelligence freshness, and local registry/filesystem states at the time of generation. "
    "This report is intended for internal cybersecurity posture management and does not constitute "
    "a legally certified regulatory compliance audit by an accredited third-party assessor."
)


class ComplianceReporter:
    """Compiles multi-source cybersecurity telemetry into structured compliance reports."""

    def __init__(
        self,
        fleet_manager: Optional[FleetManager] = None,
        history_db: Optional[HistoryDatabase] = None,
        reports_dir: Optional[Path] = None,
    ):
        self.fleet_manager = fleet_manager or FleetManager()
        self.history_db = history_db or HistoryDatabase()
        self.reports_dir = Path(reports_dir or REPORTS_DIR)
        self.reports_dir.mkdir(parents=True, exist_ok=True)

    def check_local_bitlocker_status(self) -> Dict[str, Any]:
        """
        Check local drive encryption posture.
        Uses non-destructive Windows API / WMI check if running on Windows.
        """
        result = {
            "os_platform": sys.platform,
            "encryption_supported": sys.platform.startswith("win"),
            "system_drive_encrypted": "UNKNOWN",
            "method": "API_QUERY",
            "details": "Inspection completed safely.",
        }

        if not sys.platform.startswith("win"):
            result["system_drive_encrypted"] = "NOT_APPLICABLE"
            result["details"] = "Non-Windows operating system."
            return result

        try:
            # Query Windows Registry for BitLocker OS volume status if possible
            import winreg
            try:
                with winreg.OpenKey(
                    winreg.HKEY_LOCAL_MACHINE,
                    r"SYSTEM\CurrentControlSet\Control\BitLocker",
                    0,
                    winreg.KEY_READ,
                ) as key:
                    # Key existence indicates BitLocker driver presence
                    result["system_drive_encrypted"] = "CONFIGURED"
                    result["details"] = "BitLocker subsystem registered in Windows registry."
            except FileNotFoundError:
                result["system_drive_encrypted"] = "UNCONFIGURED"
                result["details"] = "BitLocker registry entries not configured."
        except Exception as e:
            result["system_drive_encrypted"] = "UNVERIFIED"
            result["details"] = f"BitLocker check query returned: {e}"

        return result

    def collect_compliance_metrics(self) -> Dict[str, Any]:
        """Compile complete posture metrics across fleet, patch, and local security modules."""
        # 1. Fleet Statistics
        stats = self.fleet_manager.db.get_fleet_stats()
        total_endpoints = stats.get("total_endpoints", 0)
        healthy = stats.get("healthy_count", 0)
        at_risk = stats.get("at_risk_count", 0)
        offline = stats.get("offline_count", 0)
        isolated = stats.get("isolated_count", 0)

        health_pct = round((healthy / total_endpoints * 100), 1) if total_endpoints > 0 else 100.0

        # 2. Local Threat & Quarantine History
        scans_count = 0
        threats_found = 0
        quarantine_count = 0
        restored_count = 0
        try:
            history_rows = self.fleet_manager.db.get_fleet_events(severity="CRITICAL", limit=500)
            threats_found = len(history_rows)
            # Query history db for local stats if available
            conn = self.history_db._get_connection()
            with conn:
                cursor = conn.cursor()
                cursor.execute("SELECT COUNT(*) FROM scan_history")
                scans_count = cursor.fetchone()[0]
                cursor.execute("SELECT COUNT(*) FROM detections")
                db_threats = cursor.fetchone()[0]
                threats_found = max(threats_found, db_threats)
                cursor.execute("SELECT COUNT(*) FROM quarantine")
                quarantine_count = cursor.fetchone()[0]
                cursor.execute("SELECT COUNT(*) FROM quarantine WHERE restored = 1")
                restored_count = cursor.fetchone()[0]
        except Exception:
            pass

        # 3. Patch & Software Vulnerability Status
        vuln_apps = 0
        up_to_date_apps = 0
        total_inventoried = 0
        try:
            inv = self.history_db.get_software_inventory()
            total_inventoried = len(inv)
            for app in inv:
                if app.get("status") == "CONFIRMED_VULNERABLE":
                    vuln_apps += 1
                elif app.get("status") == "UP_TO_DATE":
                    up_to_date_apps += 1
        except Exception:
            pass

        # 4. Active Policies
        policies = self.fleet_manager.db.list_policies()

        # 5. Active Incidents
        active_incidents = self.fleet_manager.db.list_incidents(status="ACTIVE")

        # 6. Local Encryption Posture
        bitlocker = self.check_local_bitlocker_status()

        return {
            "report_timestamp": time.time(),
            "report_date_utc": time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime()),
            "app_name": APP_NAME,
            "app_version": APP_VERSION,
            "disclaimer": DISCLAIMER_NOTICE,
            "fleet_health": {
                "total_endpoints": total_endpoints,
                "healthy_endpoints": healthy,
                "at_risk_endpoints": at_risk,
                "offline_endpoints": offline,
                "isolated_endpoints": isolated,
                "health_compliance_percentage": health_pct,
            },
            "detection_metrics": {
                "scans_conducted": scans_count,
                "threats_detected": threats_found,
                "quarantined_threats": quarantine_count,
                "restored_items": restored_count,
            },
            "vulnerability_metrics": {
                "applications_inventoried": total_inventoried,
                "confirmed_vulnerable": vuln_apps,
                "up_to_date": up_to_date_apps,
            },
            "incident_metrics": {
                "active_incidents": len(active_incidents),
                "incidents_summary": [
                    {
                        "id": i.incident_id,
                        "title": i.title,
                        "severity": i.severity,
                        "status": i.status,
                        "affected_count": len(i.affected_endpoints),
                    }
                    for i in active_incidents[:5]
                ],
            },
            "encryption_compliance": bitlocker,
            "active_policies_count": len(policies),
        }

    def generate_markdown_report(self) -> str:
        """Render security posture and compliance report in GitHub-flavored Markdown."""
        data = self.collect_compliance_metrics()
        fh = data["fleet_health"]
        dm = data["detection_metrics"]
        vm = data["vulnerability_metrics"]
        im = data["incident_metrics"]
        enc = data["encryption_compliance"]

        lines = [
            f"# {APP_NAME} — Enterprise Security & Compliance Posture Report",
            "",
            f"**Generated:** {data['report_date_utc']}  ",
            f"**Platform Version:** {APP_NAME} v{APP_VERSION}  ",
            f"**Compliance Status:** {'PASSED' if fh['health_compliance_percentage'] >= 90 and im['active_incidents'] == 0 else 'REQUIRES_ATTENTION'}  ",
            "",
            "> [!NOTE]",
            f"> {DISCLAIMER_NOTICE}",
            "",
            "## 1. Executive Fleet Health Summary",
            "",
            f"- **Fleet Health Compliance:** `{fh['health_compliance_percentage']}%`",
            f"- **Total Managed Endpoints:** `{fh['total_endpoints']}`",
            f"- **Healthy Endpoints:** `{fh['healthy_endpoints']}`",
            f"- **At-Risk Endpoints:** `{fh['at_risk_endpoints']}`",
            f"- **Offline Endpoints:** `{fh['offline_endpoints']}`",
            f"- **Isolated Endpoints (Containment):** `{fh['isolated_endpoints']}`",
            "",
            "## 2. Detection, Mitigation & Quarantine Telemetry",
            "",
            "| Metric | Count | Operational Notes |",
            "|---|:---:|---|",
            f"| Total Scans Completed | {dm['scans_conducted']} | Real-time and on-demand scans |",
            f"| Threats Detected | {dm['threats_detected']} | High and critical malware detections |",
            f"| Items Quarantined | {dm['quarantined_threats']} | AES-256-GCM encrypted vault isolations |",
            f"| Items Restored | {dm['restored_items']} | Authenticated administrator recoveries |",
            "",
            "## 3. Vulnerability & Software Patch Audit Posture",
            "",
            f"- **Installed Software Inventoried:** `{vm['applications_inventoried']}`",
            f"- **Confirmed Vulnerable Applications (CVE Correlated):** `{vm['confirmed_vulnerable']}`",
            f"- **Verified Up-to-Date Applications:** `{vm['up_to_date']}`",
            "",
            "## 4. EDR Incidents & Endpoint Containment",
            "",
            f"- **Active High/Critical Incidents:** `{im['active_incidents']}`",
        ]

        if im["incidents_summary"]:
            lines.append("")
            lines.append("| Incident ID | Title | Severity | Affected Endpoints | Status |")
            lines.append("|---|---|:---:|:---:|:---:|")
            for inc in im["incidents_summary"]:
                lines.append(f"| `{inc['id']}` | {inc['title']} | `{inc['severity']}` | {inc['affected_count']} | `{inc['status']}` |")
        else:
            lines.append("  *No active critical security incidents recorded.*")

        lines.extend([
            "",
            "## 5. System Encryption & Hardware Controls",
            "",
            f"- **Operating System:** `{enc['os_platform']}`",
            f"- **Storage Encryption State:** `{enc['system_drive_encrypted']}`",
            f"- **Verification Assessment:** {enc['details']}",
            "",
            "---",
            f"*Report automatically generated by {APP_NAME} Enterprise Reporting Subsystem.*",
        ])

        return "\n".join(lines)

    def generate_json_report(self) -> str:
        """Render security posture and compliance report in JSON format."""
        data = self.collect_compliance_metrics()
        return json.dumps(data, indent=2)

    def export_report_to_file(self, output_path: Optional[Path] = None, format: str = "markdown") -> Path:
        """Save report to file on D: drive."""
        ts = int(time.time())
        ext = "md" if format.lower() == "markdown" else "json"
        dest = output_path or (self.reports_dir / f"compliance_report_{ts}.{ext}")

        content = self.generate_markdown_report() if format.lower() == "markdown" else self.generate_json_report()
        dest.write_text(content, encoding="utf-8")
        logger.info(f"Exported compliance report to: {dest}")
        return dest
